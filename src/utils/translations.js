// Translation function with variable replacement support
export const t = (key, lang = 'en', vars = {}) => {
  const languageTranslations = translations[lang];
  
  if (!languageTranslations) {
    console.warn(`Language "${lang}" not found, falling back to English`);
    return replaceVars(translations.en[key] || key, vars);
  }
  
  const translation = languageTranslations[key];
  
  if (!translation) {
    console.warn(`Translation key "${key}" not found for language "${lang}"`);
    return replaceVars(translations.en[key] || key, vars);
  }
  
  return replaceVars(translation, vars);
};

// Helper function to replace variables like {age} and {points}
const replaceVars = (text, vars) => {
  if (!text || typeof text !== 'string') return text;
  
  let result = text;
  Object.keys(vars).forEach(key => {
    result = result.replace(new RegExp(`\\{${key}\\}`, 'g'), vars[key]);
  });
  
  return result;
};

export default translations;
